#!/usr/bin/env node
'use strict';

/**
 * build-corpus-replay-status.js — record which corpus pairs actually reproduce.
 *
 * `pair_status: verified_pair` in corpus v0.7 is a claim that the stored
 * plaintext and ciphertext round-trip through the museum's engines. This script
 * establishes that by replaying every record in both directions and storing the
 * exceptions, so the v0.7 build does not have to re-run a full replay and the
 * claim stays auditable.
 *
 * A record reproduces when, using the replay harness's own key extraction and
 * text policies, encode(plaintext, key) equals the stored ciphertext *and*
 * decode(ciphertext, key) equals the prepared plaintext. Anything else — a
 * mismatch, a throw, a missing engine — is listed as not reproducing, with the
 * reason, and is not benchmark-eligible in v0.7.
 *
 * Run: node scripts/build-corpus-replay-status.js [--check]
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const helpers = require(path.join(ROOT, 'tests/engines/corpus-replay.js'));
const ENGINES = require(path.join(ROOT, 'js/ciphers/all-engines.js'));

const INPUT = path.join(ROOT, 'public/corpus/all.jsonl');
const OUTPUT = path.join(ROOT, 'data/corpus-v0.7-replay-status.json');
const CHECK_ONLY = process.argv.includes('--check');

function statusFor(record) {
  const engineName = helpers.engineNameFor(record.cipher_type);
  const engine = ENGINES[engineName];
  if (!engine) return { ok: false, reason: 'no-engine' };
  let key;
  let plain;
  try {
    key = helpers.extractKey(record);
    plain = helpers.expectedPlaintext(record);
  } catch (error) {
    return { ok: false, reason: 'key-extraction-threw' };
  }
  let encoded;
  try {
    // Call the engines exactly as tests/engines/corpus-replay.js does: the raw
    // stored plaintext, which the engines normalize themselves. Passing the
    // pre-prepared text instead changes the result for every engine that
    // inserts filler or folds letters, and would understate reproduction by
    // thousands of records.
    encoded = helpers.compactCiphertext(engine.encode(record.plaintext, key));
  } catch (error) {
    return { ok: false, reason: 'encode-threw' };
  }
  if (encoded !== helpers.compactCiphertext(record.ciphertext)) {
    return { ok: false, reason: 'encode-mismatch' };
  }
  let decoded;
  try {
    decoded = helpers.applyPlaintextPolicy(engine.decode(record.ciphertext, key), record);
  } catch (error) {
    return { ok: false, reason: 'decode-threw' };
  }
  if (decoded !== plain) return { ok: false, reason: 'decode-mismatch' };
  return { ok: true };
}

function main() {
  const records = fs.readFileSync(INPUT, 'utf8').split('\n').filter(Boolean).map(JSON.parse);
  const notReproducing = [];
  const reasons = {};
  for (const record of records) {
    const status = statusFor(record);
    if (status.ok) continue;
    notReproducing.push({ id: record.id, cipher_type: record.cipher_type, reason: status.reason });
    reasons[status.reason] = (reasons[status.reason] || 0) + 1;
  }
  const payload = {
    note: 'Generated by scripts/build-corpus-replay-status.js from the immutable v0.6 all.jsonl. Records listed here do not round-trip through the museum engines and are therefore not verified pairs in v0.7.',
    source: 'public/corpus/all.jsonl',
    records_tested: records.length,
    reproducing: records.length - notReproducing.length,
    not_reproducing: notReproducing.length,
    reasons,
    not_reproducing_ids: notReproducing
  };
  const contents = JSON.stringify(payload, null, 1) + '\n';
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : null;
  if (CHECK_ONLY) {
    if (current !== contents) {
      console.error('data/corpus-v0.7-replay-status.json is out of date; run node scripts/build-corpus-replay-status.js');
      process.exitCode = 1;
    } else {
      console.log(`Replay status current: ${payload.reproducing} of ${payload.records_tested} reproduce.`);
    }
    return;
  }
  fs.writeFileSync(OUTPUT, contents);
  console.log(`Replay status: ${payload.reproducing} reproduce, ${payload.not_reproducing} do not.`);
  console.log('Reasons: ' + JSON.stringify(reasons));
}

if (require.main === module) main();

module.exports = { statusFor };
