'use strict';
const assert = require('node:assert/strict');
const { test } = require('node:test');
const { engines } = require('../helpers/engine-spec');

require('../helpers/contracts').defineContractSpec('vernam');

test('vernam: published bitwise XOR example', () => {
	// Exhibit derivation: H = 01001000 (0x48), key = 10110100 (0xB4),
	// and 01001000 XOR 10110100 = 11111100 (0xFC).
	assert.equal(engines.vernam.encode('H', 'hex:b4'), 'fc');
	assert.equal(engines.vernam.decode('fc', 'hex:b4'), 'H');
});

test('vernam: generated XOR pads use all byte values and round-trip their hex annotation', () => {
  const crypto = globalThis.crypto;
  const original = crypto.getRandomValues;
  const fixture = [0x00, 0xff, 0x80, 0x7f];
  crypto.getRandomValues = bytes => {
    for (let i = 0; i < bytes.length; i++) bytes[i] = fixture[i % fixture.length];
    return bytes;
  };
  try {
    // H=0x48: XOR with 00,ff,80,7f gives 48,b7,c8,37 independently.
    const encoded = engines.vernam.encode('HHHH', '');
    assert.equal(encoded, '48b7c837\n[Key: hex:00ff807f]');
    assert.equal(engines.vernam.decode(encoded, ''), 'HHHH');
    assert.equal(engines.vernam.decode('48b7c837', 'hex:00ff807f'), 'HHHH');
  } finally {
    crypto.getRandomValues = original;
  }
});

test('vernam: generated byte pads are chunked at the Web Crypto quota', () => {
  const encoded = engines.vernam.encode('A'.repeat(70000), '');
  const match = encoded.match(/^([0-9a-f]+)\n\[Key: hex:([0-9a-f]+)\]$/);
  assert.ok(match);
  assert.equal(match[1].length, 140000);
  assert.equal(match[2].length, 140000);
  assert.equal(engines.vernam.decode(encoded, ''), 'A'.repeat(70000));
});
